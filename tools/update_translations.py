"""Extract Miner UI messages into a German catalog and a gettext template.

Run from any directory: python tools/update_translations.py [--check]
English and other translated catalogs are intentionally never overwritten.
"""

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRING = r'"(?:\\.|[^"\\])*"'


def collect_messages():
    messages = defaultdict(set)
    for path in sorted((ROOT / "scripts").glob("*.gd")):
        source = path.read_text(encoding="utf-8")
        matches = list(re.finditer(r"\btr\(\s*(" + STRING + ")", source))
        matches += list(re.finditer(r'"(?:name|group|description)":\s*(' + STRING + ")", source))
        # Arrays intentionally contain untranslated source strings. Runtime
        # translation happens after selecting the building, objective or header.
        for array in re.finditer(
            r"(?:const BUILDINGS\s*:=|var messages\s*:=|for text in)\s*\[([^\]]*)\]",
            source,
            re.S,
        ):
            for literal in re.finditer(STRING, array[1]):
                text = json.loads(literal[0])
                if text:
                    line = source.count("\n", 0, array.start()) + 1
                    messages[text].add(f"{path.relative_to(ROOT).as_posix()}:{line}")
        for match in matches:
            text = json.loads(match[1])
            if text:
                line = source.count("\n", 0, match.start()) + 1
                messages[text].add(f"{path.relative_to(ROOT).as_posix()}:{line}")
    for path in sorted((ROOT / "scenes").glob("*.tscn")):
        for line, source in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            match = re.match(r"(?:text|tooltip_text) = (" + STRING + ")$", source)
            if match and json.loads(match[1]):
                messages[json.loads(match[1])].add(f"{path.relative_to(ROOT).as_posix()}:{line}")
    return messages


def render(messages, language):
    header = (
        "Project-Id-Version: Miner\n"
        f"Language: {language}\n"
        "MIME-Version: 1.0\n"
        "Content-Type: text/plain; charset=UTF-8\n"
        "Content-Transfer-Encoding: 8bit\n"
        "Plural-Forms: nplurals=2; plural=(n != 1);\n"
    )
    quote = lambda text: json.dumps(text, ensure_ascii=False)
    lines = ["# Generated by tools/update_translations.py; source language: German.",
             'msgid ""', "msgstr " + quote(header), ""]
    for message, locations in sorted(messages.items()):
        lines += ["#: " + " ".join(sorted(locations)),
                  "msgid " + quote(message),
                  "msgstr " + quote(message if language == "de" else ""), ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check without writing files")
    args = parser.parse_args()
    messages = collect_messages()
    for filename, language in [("de.po", "de"), ("messages.pot", "")]:
        path = ROOT / "localization" / filename
        content = render(messages, language)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Outdated catalog: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Extracted'} {len(messages)} UI messages.")


if __name__ == "__main__":
    main()
